export type AppLanguage = "vi" | "en";
export type ExtendedThemeMode = "system" | "dark" | "light" | "oled";

export function normalizeLanguage(value?: string | null): AppLanguage {
  return value === "en" ? "en" : "vi";
}

export function normalizeExtendedTheme(value?: string | null): ExtendedThemeMode {
  if (value === "system" || value === "dark" || value === "light" || value === "oled") {
    return value;
  }
  return "dark";
}

